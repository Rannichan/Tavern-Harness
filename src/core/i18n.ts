function detectBrowserLanguage(): LangKey {
  const nav = (typeof navigator !== 'undefined' ? navigator.language : '') || '';
  const lower = nav.toLowerCase();
  if (lower.startsWith('zh')) {
    if (lower.includes('tw') || lower.includes('hk') || lower.includes('hant') || lower.includes('mo')) return 'zh-TW';
    return 'zh-CN';
  }
  return 'en';
}

let currentLang: LangKey = detectBrowserLanguage();
const listeners = new Set<() => void>();

/** 设置当前语言（null = 跟随浏览器），同步 <html lang> 并通知订阅者 */
export function setLanguage(lang: AppLanguage | null): void {
  currentLang = lang ?? detectBrowserLanguage();
  try {
    document.documentElement.lang = currentLang;
  } catch {
    /* SSR / 非浏览器环境忽略 */
  }
  listeners.forEach((fn) => fn());
}

export function currentLanguage(): LangKey {
  return currentLang;
}

/** 当前语言对应的 Intl locale（用于日期/数字格式化） */
export function currentLocale(): string {
  return currentLang === 'zh-CN' ? 'zh-CN' : currentLang === 'zh-TW' ? 'zh-TW' : 'en-US';
}

function translateFor(lang: LangKey, key: string, params?: Record<string, string | number>): string {
  const table = MESSAGES[lang] ?? MESSAGES['zh-CN'];
  let s = table[key] ?? MESSAGES['zh-CN'][key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

function subscribe(fn: () => void): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

function getSnapshot(): LangKey {
  return currentLang;
}

/**
 * React 响应式翻译 hook：语言切换时自动重渲染。
 * 用法：const t = useT(); t('nav.chat') / t('toast.genFailed', { msg })
 */
export function useT() {
  const lang = useSyncExternalStore(subscribe, getSnapshot, getSnapshot);
  return useCallback(
    (key: string, params?: Record<string, string | number>) => translateFor(lang, key, params),
    [lang]
  );
}

/** 静态翻译：读当前语言快照（store / 工具执行器使用） */
export function translate(key: string, params?: Record<string, string | number>): string {
  return translateFor(currentLang, key, params);
}